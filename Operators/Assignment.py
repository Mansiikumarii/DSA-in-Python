'''
It is used to assign a value to variables. It is denoted by the symbol =. The variable on the left side of the operator is called the left-hand side (LHS) and the value on the right side is called the right-hand side (RHS). The assignment operator evaluates the RHS and assigns the resulting value to the LHS variable.
+=
-=
*=
/=
%=
//=
**=
&=
'''
a=10
b=20
c=30
a,b,c = a+b, b+c, c+a
print(a) # 30
print(b) # 50
print(c) # 40

