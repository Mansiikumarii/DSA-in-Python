#Controls what is printed at the end of the line. By default, it is a new line character (\n)
print(2, end=",")
print(3)
print(4)

print(2,end=",")
print(3, end=",")
print(4, end=";")

print("Apple", end=",")
print("Virat")
print(2023, end = "#")

